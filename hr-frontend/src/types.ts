// Mirrors app/schemas/*.py on the backend. Keep in sync with those files.

export type UserRole = 'admin' | 'hr' | 'manager';

export interface User {
  id: number;
  email: string;
  full_name?: string | null;
  role: UserRole;
  is_active: boolean;
  created_at: string;
}

export interface EmployeeBase {
  full_name: string;
  department: string;
  performance_trend: 'improving' | 'stable' | 'declining';
  // Which manager (User with role='manager') owns this employee. null =
  // unassigned. Lives on EmployeeBase (not just Employee) so the add/edit
  // form can read and submit it like any other field.
  managed_by_user_id: number | null;
  tenure_years: number;
  current_salary: number;
  attendance_pct: number;
  avg_login_delay_min: number;
  tasks_assigned: number;
  tasks_completed_on_time: number;
  task_completion_rate: number;
  quality_score: number;
  manager_rating: number;
  peer_rating: number;
  overtime_hours_month: number;
  past_leave_requests: number;
  past_leave_approved_rate: number;
}

export interface Employee extends EmployeeBase {
  id: number;
  created_at: string;
  updated_at: string;
}

export interface TopFeature {
  feature: string;
  value: number | string;
  impact: number | null;
}

export interface TargetResult {
  prediction: string;
  confidence: number | null;
  top_features: TopFeature[];
}

export interface PredictResponse {
  employee_id: number | null;
  results: Record<string, TargetResult>;
}

export type ApprovalStatus = 'pending' | 'approved' | 'rejected';

export interface PredictionHistory {
  id: number;
  employee_id: number;
  target: string;
  prediction: string;
  confidence: number | null;
  top_features: TopFeature[] | null;
  status: ApprovalStatus;
  reviewed_by_user_id: number | null;
  reviewed_at: string | null;
  review_note: string | null;
  created_at: string;
}

export interface AuditLogEntry extends PredictionHistory {
  employee_name: string;
  requested_by_name: string | null;
  reviewed_by_name: string | null;
}

export interface FormOptions {
  departments: string[];
  performance_trends: string[];
  numeric_fields: string[];
}

// ---- recruitment (AI resume matcher) ----

export interface JobDescription {
  id: number;
  title: string;
  department: string | null;
  raw_text: string;
  created_at: string;
  candidate_count: number;
}

export interface Candidate {
  id: number;
  job_description_id: number;
  full_name: string | null;
  file_name: string;
  created_at: string;
}

export interface MatchBreakdown {
  skills_match: number;
  experience_match: number;
  education_match: number;
}

export interface InterviewQuestion {
  question: string;
  why: string;
}

export interface MatchReport {
  id: number;
  candidate_id: number;
  match_score: number;
  semantic_similarity?: number | null;
  verdict: string;
  summary: string;
  matched_keywords: string[];
  missing_keywords: string[];
  strengths: string[];
  gaps: string[];
  breakdown: MatchBreakdown;
  interview_questions: InterviewQuestion[] | null;
  created_at: string;
}

export interface RankingEntry {
  candidate_id: number;
  candidate_name: string | null;
  file_name: string;
  match_score: number;
  verdict: string;
  report_id: number;
}

export interface RankingResult {
  job_description_id: number;
  job_title: string;
  ranking: RankingEntry[];
}

export interface BiasFlag {
  phrase: string;
  category: string;
  why: string;
  suggestion: string;
}

export interface BiasCheckResult {
  overall_risk: 'Low' | 'Moderate' | 'High' | string;
  summary: string;
  flags: BiasFlag[];
}

export interface ResumeDoctorResult {
  overall_feedback: string;
  missing_keywords_to_add: string[];
  section_suggestions: { section: string; suggestion: string }[];
  rewrite_example: string;
}

export interface VerdictCount {
  verdict: string;
  count: number;
}

export interface PipelineSnapshot {
  open_job_descriptions: number;
  candidates_uploaded: number;
  reports_generated: number;
  average_match_score: number | null;
  verdict_breakdown: VerdictCount[];
  top_missing_keywords: string[];
}

// ---- model benchmarking + fairness (generated by scripts/train_models.py) ----

export interface ShippedModel {
  target: string;
  best_model: string;
  val_macro_f1: number;
  test_accuracy: number;
  test_macro_f1: number;
}

export interface BenchmarkVariant {
  target: string;
  model: string;
  shipped: boolean;
  test_accuracy: number;
  test_macro_f1: number;
  test_per_class_f1: Record<string, number>;
}

export interface ClassImbalanceHandling {
  target: string;
  minority_class: string;
  minority_class_share_of_data: number;
  xgboost_no_weighting_minority_f1: number;
  xgboost_balanced_minority_f1: number;
  xgboost_no_weighting_macro_f1: number;
  xgboost_balanced_macro_f1: number;
}

export interface BenchmarkReport {
  shipped_models: ShippedModel[];
  all_variants: BenchmarkVariant[];
  class_imbalance_handling: ClassImbalanceHandling;
}

export interface FairnessOutcomeReport {
  outcome: string;
  group_col: string;
  selection_rates?: Record<string, number>;
  demographic_parity_difference?: number;
  disparate_impact_ratio?: number;
  flagged?: boolean;
  per_class?: Record<string, FairnessOutcomeReport>;
  any_class_flagged?: boolean;
}

export interface FairnessReport {
  group_col: string;
  note: string;
  reports: Record<string, FairnessOutcomeReport>;
}