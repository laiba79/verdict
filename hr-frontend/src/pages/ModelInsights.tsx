import { useEffect, useState } from 'react';
import { BarChart3, ShieldAlert, ShieldCheck, Loader2, AlertCircle, TrendingUp } from 'lucide-react';
import { getModelBenchmark, getFairnessAudit } from '../services/resources';
import { apiErrorMessage } from '../services/api';
import type { BenchmarkReport, FairnessReport, FairnessOutcomeReport } from '../types';
import StatCard from '../components/StatCard';

const TARGET_LABELS: Record<string, string> = {
  salary_change: 'Salary Change',
  wfh_allowed: 'WFH Allowed',
  must_work_saturday: 'Must Work Saturday',
};

const FairnessRow = ({ label, report }: { label: string; report: FairnessOutcomeReport }) => {
  const flagged = report.flagged;
  return (
    <div className={`flex items-center justify-between gap-4 px-4 py-3 rounded-xl border ${
      flagged
        ? 'border-reject-200 dark:border-reject-500/20 bg-reject-50/60 dark:bg-reject-500/[0.06]'
        : 'border-approve-200 dark:border-approve-500/20 bg-approve-50/60 dark:bg-approve-500/[0.06]'
    }`}>
      <div className="flex items-center gap-2.5 min-w-0">
        {flagged
          ? <ShieldAlert className="w-4 h-4 text-reject-600 dark:text-reject-400 shrink-0" />
          : <ShieldCheck className="w-4 h-4 text-approve-600 dark:text-approve-400 shrink-0" />}
        <span className="text-sm font-medium text-slate-700 dark:text-slate-200 truncate">{label}</span>
      </div>
      <div className="flex items-center gap-4 text-xs text-slate-500 dark:text-slate-400 shrink-0 tabular">
        <span>DPD {report.demographic_parity_difference?.toFixed(3)}</span>
        <span>DIR {report.disparate_impact_ratio?.toFixed(3)}</span>
      </div>
    </div>
  );
};

const ModelInsights = () => {
  const [benchmark, setBenchmark] = useState<BenchmarkReport | null>(null);
  const [fairness, setFairness] = useState<FairnessReport | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    (async () => {
      try {
        const [b, f] = await Promise.all([getModelBenchmark(), getFairnessAudit()]);
        setBenchmark(b);
        setFairness(f);
      } catch (err) {
        setError(apiErrorMessage(err, 'Could not load model insights. Have you run scripts/train_models.py yet?'));
      } finally {
        setLoading(false);
      }
    })();
  }, []);

  if (loading) {
    return (
      <div className="flex items-center justify-center py-24 text-slate-400">
        <Loader2 className="w-5 h-5 animate-spin mr-2" /> Loading model insights…
      </div>
    );
  }

  if (error) {
    return (
      <div className="panel p-6 flex items-start gap-3 border-reject-200 dark:border-reject-500/20">
        <AlertCircle className="w-5 h-5 text-reject-600 dark:text-reject-400 shrink-0 mt-0.5" />
        <div>
          <div className="font-medium text-slate-800 dark:text-slate-100">Couldn't load model insights</div>
          <div className="text-sm text-slate-500 dark:text-slate-400 mt-1">{error}</div>
        </div>
      </div>
    );
  }

  if (!benchmark || !fairness) return null;

  const imbalance = benchmark.class_imbalance_handling;

  return (
    <div className="space-y-8 animate-fadeUp">
      <div>
        <h1 className="font-display text-2xl font-semibold text-slate-900 dark:text-white">Model Insights</h1>
        <p className="text-sm text-slate-500 dark:text-slate-400 mt-1">
          Benchmark comparison across model families and a department-level fairness audit,
          generated by <code className="text-xs bg-slate-100 dark:bg-white/10 px-1.5 py-0.5 rounded">scripts/train_models.py</code>.
        </p>
      </div>

      {/* Shipped models */}
      <div className="grid grid-cols-1 md:grid-cols-3 gap-5">
        {benchmark.shipped_models.map((m) => (
          <StatCard
            key={m.target}
            label={TARGET_LABELS[m.target] ?? m.target}
            value={m.best_model}
            icon={TrendingUp}
            accent="primary"
            hint={`Test macro F1: ${m.test_macro_f1.toFixed(3)} · Accuracy: ${m.test_accuracy.toFixed(3)}`}
          />
        ))}
      </div>

      {/* Benchmark tables */}
      <div className="panel p-6">
        <div className="flex items-center gap-2.5 mb-5">
          <BarChart3 className="w-[18px] h-[18px] text-primary-600 dark:text-primary-400" />
          <h2 className="font-display text-lg font-semibold text-slate-900 dark:text-white">Model Benchmark</h2>
        </div>
        <p className="text-xs text-slate-400 dark:text-slate-500 mb-5">
          Model selection uses validation macro-F1 only. Test-set numbers below are shown for comparison
          and never influenced which model shipped.
        </p>
        <div className="space-y-6">
          {Object.keys(TARGET_LABELS).map((target) => {
            const rows = benchmark.all_variants.filter((v) => v.target === target);
            if (!rows.length) return null;
            return (
              <div key={target}>
                <div className="text-sm font-semibold text-slate-700 dark:text-slate-200 mb-2">
                  {TARGET_LABELS[target]}
                </div>
                <div className="overflow-x-auto rounded-xl border border-slate-200 dark:border-white/[0.06]">
                  <table className="w-full text-sm">
                    <thead>
                      <tr className="bg-slate-50 dark:bg-white/[0.03] text-left text-xs text-slate-500 dark:text-slate-400">
                        <th className="px-4 py-2.5 font-medium">Model</th>
                        <th className="px-4 py-2.5 font-medium">Test Accuracy</th>
                        <th className="px-4 py-2.5 font-medium">Test Macro F1</th>
                        <th className="px-4 py-2.5 font-medium">Shipped</th>
                      </tr>
                    </thead>
                    <tbody>
                      {rows.map((r) => (
                        <tr key={r.model} className={`border-t border-slate-100 dark:border-white/[0.04] tabular ${
                          r.shipped ? 'bg-primary-50/50 dark:bg-primary-500/[0.06]' : ''
                        }`}>
                          <td className="px-4 py-2.5 text-slate-700 dark:text-slate-200">{r.model}</td>
                          <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300">{r.test_accuracy.toFixed(3)}</td>
                          <td className="px-4 py-2.5 text-slate-600 dark:text-slate-300">{r.test_macro_f1.toFixed(3)}</td>
                          <td className="px-4 py-2.5">
                            {r.shipped && (
                              <span className="text-[11px] font-medium px-2 py-0.5 rounded-full bg-primary-100 text-primary-700 dark:bg-primary-500/15 dark:text-primary-400">
                                Shipped
                              </span>
                            )}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              </div>
            );
          })}
        </div>
      </div>

      {/* Class imbalance handling */}
      <div className="panel p-6">
        <h2 className="font-display text-lg font-semibold text-slate-900 dark:text-white mb-1">
          Class Imbalance Handling
        </h2>
        <p className="text-sm text-slate-500 dark:text-slate-400 mb-5">
          <code className="text-xs bg-slate-100 dark:bg-white/10 px-1.5 py-0.5 rounded">salary_change = {imbalance.minority_class}</code>{' '}
          is only <strong>{(imbalance.minority_class_share_of_data * 100).toFixed(1)}%</strong> of the dataset.
          Per-sample class weighting was applied to XGBoost to correct for it.
        </p>
        <div className="grid grid-cols-2 gap-4 max-w-md">
          <div className="p-4 rounded-xl bg-slate-50 dark:bg-white/[0.03]">
            <div className="text-xs text-slate-400 dark:text-slate-500 mb-1">No weighting</div>
            <div className="font-display text-2xl font-semibold text-slate-800 dark:text-slate-100 tabular">
              {imbalance.xgboost_no_weighting_minority_f1.toFixed(3)}
            </div>
            <div className="text-[11px] text-slate-400 dark:text-slate-500 mt-0.5">minority-class F1</div>
          </div>
          <div className="p-4 rounded-xl bg-approve-50/60 dark:bg-approve-500/[0.06]">
            <div className="text-xs text-slate-400 dark:text-slate-500 mb-1">Balanced</div>
            <div className="font-display text-2xl font-semibold text-approve-700 dark:text-approve-400 tabular">
              {imbalance.xgboost_balanced_minority_f1.toFixed(3)}
            </div>
            <div className="text-[11px] text-slate-400 dark:text-slate-500 mt-0.5">minority-class F1</div>
          </div>
        </div>
      </div>

      {/* Fairness audit */}
      <div className="panel p-6">
        <h2 className="font-display text-lg font-semibold text-slate-900 dark:text-white mb-1">
          Fairness Audit
        </h2>
        <p className="text-sm text-slate-500 dark:text-slate-400 mb-5">{fairness.note}</p>
        <div className="space-y-3">
          {Object.entries(fairness.reports).map(([target, report]) => {
            if (report.per_class) {
              return (
                <div key={target}>
                  <div className="text-sm font-semibold text-slate-700 dark:text-slate-200 mb-2">
                    {TARGET_LABELS[target] ?? target}
                  </div>
                  <div className="space-y-2">
                    {Object.entries(report.per_class).map(([cls, clsReport]) => (
                      <FairnessRow key={cls} label={`${TARGET_LABELS[target] ?? target} = ${cls}`} report={clsReport} />
                    ))}
                  </div>
                </div>
              );
            }
            return (
              <div key={target}>
                <div className="text-sm font-semibold text-slate-700 dark:text-slate-200 mb-2">
                  {TARGET_LABELS[target] ?? target}
                </div>
                <FairnessRow label={TARGET_LABELS[target] ?? target} report={report} />
              </div>
            );
          })}
        </div>
        <p className="text-[11px] text-slate-400 dark:text-slate-500 mt-5">
          DPD = Demographic Parity Difference (flag above 0.20) · DIR = Disparate Impact Ratio (flag below 0.80, EEOC four-fifths rule)
        </p>
      </div>
    </div>
  );
};

export default ModelInsights;
