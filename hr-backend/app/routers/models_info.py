import json
import os

from fastapi import APIRouter, Depends, HTTPException

from app.auth.dependencies import get_current_user
from app.models.user import User
from app.ml.loader import registry
from app.ml.predictor import DEPARTMENTS, TRENDS, RAW_NUMERIC_FIELDS

router = APIRouter(prefix="/meta", tags=["meta"])

OUTPUTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "outputs")


def _read_report(filename: str) -> dict:
    path = os.path.join(OUTPUTS_DIR, filename)
    if not os.path.exists(path):
        raise HTTPException(
            status_code=404,
            detail=f"{filename} not found. Run `python scripts/train_models.py` to generate it.",
        )
    with open(path) as f:
        return json.load(f)


@router.get("/form-options")
def form_options():
    """Lets the frontend build its form dynamically instead of
    hardcoding department/trend lists in two places."""
    return {
        "departments": DEPARTMENTS,
        "performance_trends": TRENDS,
        "numeric_fields": RAW_NUMERIC_FIELDS,
    }


@router.get("/models-status")
def models_status(_current_user: User = Depends(get_current_user)):
    return {
        "ready": registry.is_ready(),
        "available_targets": registry.available_targets(),
        "explainers_loaded": list(registry.explainers.keys()),
    }


@router.get("/benchmark")
def model_benchmark(_current_user: User = Depends(get_current_user)):
    """Model comparison report (LogisticRegression / RandomForest /
    XGBoost, with + without class-imbalance weighting) generated by
    scripts/train_models.py."""
    return _read_report("benchmark_results.json")


@router.get("/fairness")
def fairness_audit(_current_user: User = Depends(get_current_user)):
    """Department-level fairness audit (demographic parity + disparate
    impact) on the shipped models' predictions, generated by
    scripts/train_models.py."""
    return _read_report("fairness_report.json")
